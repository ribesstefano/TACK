def _get_manual_cell_mapping(
    row: pd.Series,
) -> pd.Series:
    """ Get the manually curated cell line mapping for a given row.
    If the cell type is not in the manual mapping, return None for the
    standardized cell line. Used for logging and analysis purposes.
    
    Args:
        row: A row of the dataframe containing cell type information.
        manual_cell_mapping: A dictionary mapping raw cell types to standardized cell lines.
        
    Returns:
        A pandas Series with the original cell type, the manually curated cell line (or None), and the article DOI for reference.
    """
    article_doi = 'https://doi.org/' + row['Article DOI'].split(';')[0].strip() if pd.notna(row['Article DOI']) else None
    cell_cols = [col for col in row.index if 'Cell Type' in col]
    cell_type = row[cell_cols[0]] if cell_cols else pd.NA
     # If there are multiple cell type columns, prefer the one that is not NaN
    if pd.isna(cell_type):
        return pd.Series({
            'Cell Type': cell_type,
            'Manually Curated Cell Line (in CelloSaurus)': None,
            'Article DOI': article_doi,
        })
    if cell_type not in MANUAL_CELL_MAPPING:
        return pd.Series({
            'Cell Type': cell_type,
            'Manually Curated Cell Line (in CelloSaurus)': None,
            'Article DOI': article_doi,
        })
    standardized = MANUAL_CELL_MAPPING[cell_type]
    return pd.Series({
        'Cell Type': cell_type,
        'Manually Curated Cell Line (in CelloSaurus)': standardized,
        'Article DOI': article_doi,
    })


def log_manual_cell_mapping(
    df_dict: Dict[str, pd.DataFrame],
    logger: logging.Logger,
) -> None:
    """ Log the manually curated cell line mappings for all dataframes in the given dictionary. """
    tmp = []
    for _, df in df_dict.items():
        tmp.append(df.apply(_get_manual_cell_mapping).dropna())

    tmp = pd.concat(tmp, axis=0).drop_duplicates().reset_index(drop=True)
    logger.info('Manually curated cell lines:\n' + str(tmp.to_markdown()))


def standardize_cell_line(
    cell_name: str,
    cell_embedding: CellEmbedding,
    manual_cell_mapping: Optional[Dict[str, str]] = None,
    fuzzy_matching_threshold: float = 0.0,
    logger: Optional[logging.Logger] = None,
) -> Tuple[Optional[str], Optional[str]]:
    """ Standardize a cell line name using the Cellosaurus embeddings and manual mapping.
    
    Args:
        cell_name (str): The raw cell line name to standardize.
        cell_embedding (CellEmbedding): An instance of CellEmbedding containing the cell line data.
        manual_cell_mapping (Optional[Dict[str, str]]): A dictionary mapping raw cell types to standardized cell lines.
        fuzzy_matching_threshold (float): A threshold for fuzzy matching. If > 0.0, the function will attempt to find a fuzzy match in the Cellosaurus embeddings if the exact match is not found. The value should be between 0.0 and 1.0, where 1.0 means an exact match.
        logger (logging.Logger, optional): A logger for logging warnings. If None, no warnings will be logged.

    Returns:
        Tuple[Optional[str], Optional[str]]: A tuple containing the standardized cell line name and its corresponding Cell ID. If the cell line cannot be standardized, returns (None, None).
    """
    if pd.isna(cell_name):
        return None, None
    
    if manual_cell_mapping is None:
        manual_cell_mapping = MANUAL_CELL_MAPPING
    else:
        # Merge the provided manual mapping with the default one, giving
        # precedence to the provided mapping
        manual_cell_mapping = {**MANUAL_CELL_MAPPING, **manual_cell_mapping}

    # First, apply manual mapping if available
    std_cell_name = manual_cell_mapping.get(cell_name, cell_name)
    if logger is not None:
        logger.debug(f'Standardizing cell line: Original="{cell_name}", After manual mapping="{std_cell_name}"')

    # Check if the cell line is already standardized
    if std_cell_name in cell_embedding.cell2data:
        return std_cell_name, cell_embedding.cell2cell_id.get(std_cell_name)
    if std_cell_name in cell_embedding.synonym2cell_line:
        std_cell_name = cell_embedding.synonym2cell_line[std_cell_name]
    elif std_cell_name not in cell_embedding.cell2data:
        # Try fuzzy matching if a score threshold is provided
        if fuzzy_matching_threshold > 0.0:
            std_cell_name, _ = cell_embedding.get_fuzzy_cell_line(
                std_cell_name,
                min_similarity_score=fuzzy_matching_threshold * 100,  # Convert to percentage
            )
            if std_cell_name == cell_embedding.not_found_description:
                if logger is not None:
                    logger.warning(f'WARNING: No fuzzy match found for cell line: {cell_name} with score >= {fuzzy_matching_threshold}')
                return None, None
        else:
            # Print a warning if the cell line is not found
            if logger is not None:
                logger.warning(f'WARNING: Cell line not found in Cellosaurus embeddings: {cell_name} (after manual mapping: {std_cell_name})')
            return None, None

    cell_id = cell_embedding.cell2cell_id.get(std_cell_name)
    return std_cell_name, cell_id
    


